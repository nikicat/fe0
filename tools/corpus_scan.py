#!/usr/bin/env python3
"""Classify official Fe test programs by how close their code-under-test is to Fe0.

The #[test] functions are the harness (they stay official Fe); only the rest of the file
(contracts, msgs, free fns, consts) would be compiled by Fe0.

  ready  - the subject uses only Fe0 features
  near   - only mechanical blockers: sol("...") selectors (precomputed with keccak),
           unit recv arms without `{}`, `use` lines, fn-only files that need a wrapper contract
  out    - needs features outside Fe0

ponytail: regex scan, not a parser; misclassifications get fixed by hand when a file is adopted.

usage: corpus_scan.py DIR... > CORPUS.md
"""
import re
import sys
from collections import Counter
from pathlib import Path

HARD = {
    "struct/enum/impl/trait/type": r"\b(struct|enum|impl|trait|type|mod|extern|unsafe)\b",
    "for/match": r"\b(for|match)\b",
    "generics": r"\bfn\s+\w+\s*<|<\s*\w+\s*:\s*\w",
    "with/closures": r"\bwith\s*\(|\|\s*\w*\s*(:\s*\w+)?\s*\|",
    "method/field access": r"[A-Za-z_)\]]\.[A-Za-z_]",
    "path call (a::b)": r"\w::\w",
    "casts": r"\bas\b",
    "pow": r"\*\*",
    "arrays/index": r"(?<!#)\[[^\]]*\]",
    "contract-level uses": r"\bcontract\s+\w+\s+uses\b",
    "events/payable/attrs": r"#\[(?!selector\b)(?!test\b)\w+",
    "macros other than assert!": r"\b(?!assert\b)\w+!\s*\(",
    "const fn": r"\bconst\s+fn\b",
    "for/loop/yield": r"\b(loop|yield)\b",
}
ALLOWED_TYPES = {"u256", "bool", "Address"}
TYPE_POS = r"(?:->|:)\s*(?:mut\s+|own\s+|ref\s+)?([A-Za-z_][A-Za-z0-9_]*)"


def strip(src):
    src = re.sub(r"//[^\n]*", "", src)
    return re.sub(r'"([^"\\]|\\.)*"', '""', src)


def split_tests(src):
    """Return (subject, n_tests): src with every #[test...] fn removed."""
    out, i, n = [], 0, 0
    for m in re.finditer(r"#\[test[^\]]*\]", src):
        if m.start() < i:
            continue
        out.append(src[i:m.start()])
        j = src.index("{", m.end())
        depth = 0
        for k in range(j, len(src)):
            depth += {"{": 1, "}": -1}.get(src[k], 0)
            if depth == 0:
                break
        i, n = k + 1, n + 1
    out.append(src[i:])
    return "".join(out), n


def classify(path):
    raw = path.read_text()
    subject, n_tests = split_tests(strip(raw))
    near, hard = set(), set()
    if re.search(r"\bsol\s*\(", raw):
        near.add("sol() selectors")
        subject = re.sub(r"sol\s*\(\s*\"\"\s*\)", "0", subject)
    if re.search(r"^\s*use\b", subject, re.M):
        near.add("use lines")
        subject = re.sub(r"^\s*(pub\s+)?use\b[^\n]*", "", subject, flags=re.M)
    has_contract = re.search(r"\bcontract\s+\w+", subject)
    if not has_contract and re.search(r"\bfn\s+\w+", subject):
        near.add("fn-only (needs wrapper contract)")
    if not re.search(r"\b(fn|contract)\s+\w+", subject):
        hard.add("no subject")
    for name, rx in HARD.items():
        if re.search(rx, subject):
            hard.add(name)
    for t in re.findall(TYPE_POS, subject):
        if t not in ALLOWED_TYPES and t not in {"mut", "uses"} and not t[0].islower():
            hard.add(f"type {t}")
        elif t[0].islower() and t not in ALLOWED_TYPES and re.fullmatch(r"[ui]\d+", t):
            hard.add(f"type {t}")
    kind = "out" if hard else ("near" if near else "ready")
    return kind, sorted(near), sorted(hard), n_tests, len(raw.splitlines())


def main(dirs):
    rows = []
    for d in dirs:
        for p in sorted(Path(d).glob("*.fe")):
            rows.append((p, *classify(p)))
    kinds = Counter(r[1] for r in rows)
    blockers = Counter(b for r in rows for b in r[3])
    one_blocker = Counter(r[3][0] for r in rows if len(r[3]) == 1)
    print("# Corpus scan\n")
    print(f"Generated by `tools/corpus_scan.py` over: {', '.join(dirs)}\n")
    print(f"| kind | files |\n|---|---|")
    for k in ("ready", "near", "out"):
        print(f"| {k} | {kinds[k]} |")
    print("\n## Blockers (files affected)\n\n| blocker | files | only blocker in |\n|---|---|---|")
    for b, n in blockers.most_common():
        print(f"| {b} | {n} | {one_blocker[b]} |")
    for k in ("ready", "near"):
        print(f"\n## {k}\n\n| file | lines | tests | mechanical edits |\n|---|---|---|---|")
        for p, kind, near, hard, nt, nl in rows:
            if kind == k:
                print(f"| `{p.parent.name}/{p.name}` | {nl} | {nt} | {', '.join(near) or '-'} |")


if __name__ == "__main__":
    main(sys.argv[1:])
