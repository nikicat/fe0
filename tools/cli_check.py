#!/usr/bin/env python3
"""Check the native CLI (fe0-cli) against Fe0 on the EVM.

It builds fe0-cli as a native executable and runs it on every program of corpus/ and
corpus/gen/, and on every reject program of corpus/reject/:

- for each program, the CLI must exit with 0. Its hex goes into a test that compiles the
  program with Fe0 on the EVM, and that test checks that both codes are the same, byte for byte;
- for each reject program, the CLI must exit with 1 and print the error of the program's
  `// expect:` header.

It also checks that fe0-cli/src/messages.fe has a message for each error code of
fe0/src/diag.fe.

With --no-run, it still builds and runs the CLI and checks the messages.
"""
import re
import shutil
import subprocess
import sys
import tomllib
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from enum import IntEnum
from pathlib import Path
from typing import NamedTuple, Self

import embed
import fegen
import gen
from embed import FailureMessage
from fegen import ROOT, CodeDiffers, Diag, Failure, FeLine, FeName, FeSource, Rejected, TestName, Wei

CLI: Path = ROOT / "fe0-cli"
# The executable that `fe build` writes. It is named after the ingot.
EXE: Path = ROOT / "out/cli" / tomllib.loads((CLI / "fe.toml").read_text())["ingot"]["name"]
OUT: Path = ROOT / "out/cli-check"


class ExitCode(IntEnum):
    """An exit code of the CLI (fe0-cli/src/lib.fe)."""

    COMPILED = 0
    REJECTED = 1


# The last line that the CLI prints on stderr for an error, such as `<stdin>:5:5: N014 …`.
ERROR_LINE: re.Pattern[str] = re.compile(rf"<stdin>:{fegen.POS}: {fegen.CODE} .*")
WARNING: re.Pattern[str] = re.compile(rf"<stdin>:{fegen.POS}: warning: {fegen.CODE} .*")
# What the CLI prints on stdout for a program that it compiles: the code in lowercase hex.
HEX: re.Pattern[str] = re.compile(r"(?:[0-9a-f]{2})+\n")


def build() -> None:
    """Builds the CLI. Exits as `fegen.fe_build` does."""
    fegen.fe_build(CLI, EXE.parent, "--backend", "native", "-e", "executable")


@dataclass
class CliProgram:
    """A program, the CLI's code for it, and the test that checks the code on the EVM."""

    # corpus/X.fe or corpus/gen/sN.fe, relative to ROOT.
    path: Path
    source: FeSource
    code: bytes

    @property
    def test(self) -> TestName:
        return TestName(f"cli_{self.path.stem}")

    @property
    def runner(self) -> FeName:
        return FeName(f"check_{self.path.stem}")

    def module_text(self) -> FeSource:
        same = f"difftest::same_code({fegen.lit(self.source)}, {fegen.lit(self.code.hex())})"
        lines = [FeLine(f"// Generated by tools/cli_check.py from {self.path}."),
                 fegen.difftest_use("fe0"), FeLine(""), FeLine(f"pub fn {self.runner}() {{"),
                 FeLine(f"    {same}"), FeLine("}"), FeLine("")]
        lines += fegen.evm_test(self.test, Wei(0), [FeLine(f"{self.runner}()")])
        return fegen.source(lines)

    def explain(self, failure: Failure) -> FailureMessage | None:
        match failure:
            case CodeDiffers(offset):
                return FailureMessage(f"{self.path}: the CLI's code differs from Fe0's on the EVM"
                                      f" at byte {offset}")
            case Rejected() as r:
                return FailureMessage(f"{self.path}: the CLI accepts it, but Fe0 on the EVM rejects"
                                      f" it with {r.diag.describe(self.source)}")
        return None


class Run(NamedTuple):
    """What the CLI did with one program."""

    # Relative to ROOT.
    path: Path
    source: FeSource
    # Any exit code, not only an `ExitCode`: the CLI may also crash.
    exit_code: int
    stdout: str
    stderr: str

    @classmethod
    def of(cls, path: Path, source: FeSource) -> Self:
        """Runs the CLI with `source` on stdin. `source` is the text of the program at `path`."""
        r = subprocess.run([str(EXE)], input=source, capture_output=True, text=True)
        return cls(path, source, r.returncode, r.stdout, r.stderr)

    @classmethod
    def read(cls, path: Path) -> Self:
        """Runs the CLI on the program at `path`."""
        return cls.of(path, FeSource((ROOT / path).read_text()))

    def compiled(self) -> bool:
        """Returns whether the CLI exited with 0, printed hex on stdout and only warnings on
        stderr."""
        return (self.exit_code == ExitCode.COMPILED and HEX.fullmatch(self.stdout) is not None
                and all(map(WARNING.fullmatch, self.stderr.splitlines())))

    def program(self) -> CliProgram:
        """Returns the program with the code that the CLI printed. Errors when stdout is not hex.
        A run that `compiled` always has hex."""
        return CliProgram(self.path, self.source, bytes.fromhex(self.stdout))

    def error(self) -> Diag | None:
        """Returns the error that the CLI rejected the program with, or None when it did not exit
        with 1 or did not end stderr with an error.

        Errors as `Diag.matched` does.
        """
        lines = self.stderr.splitlines()
        m = ERROR_LINE.fullmatch(lines[-1]) if lines else None
        if self.exit_code != ExitCode.REJECTED or not m:
            return None
        return Diag.matched(m, self.source)

    def said(self) -> str:
        """Returns the exit code of the CLI, the start of its stdout and its stderr, to quote in a
        failure."""
        return (f"exit code {self.exit_code}, stdout {self.stdout[:80]!r},"
                f" stderr:\n{self.stderr.rstrip()}")


@dataclass(frozen=True)
class UncompiledProgram:
    """A program that the CLI did not compile cleanly."""

    # Relative to ROOT.
    path: Path
    # What the CLI did instead, as `Run.said` quotes it.
    said: str

    def __str__(self) -> str:
        return f"{self.path}: the CLI does not compile it cleanly: {self.said}"


@dataclass(frozen=True)
class MisjudgedReject:
    """A reject program that the CLI does not reject with the error of its header."""

    # Relative to ROOT.
    path: Path
    # What the CLI did instead.
    reason: str

    def __str__(self) -> str:
        return f"{self.path}: {self.reason}"


def misjudgement(r: embed.Reject) -> MisjudgedReject | None:
    """Runs the CLI on the reject program `r`. Returns what the CLI got wrong, or None when it
    rejects `r` with the error of `r`'s header."""
    run = Run.of(r.path, r.source)
    got = run.error()
    if got is None:
        return MisjudgedReject(r.path, f"the CLI does not reject it: {run.said()}")
    if got != r.expected:
        return MisjudgedReject(r.path, f"the CLI gives {got.describe(r.source)},"
                                       f" expected {r.expected.describe(r.source)}")
    return None


# A DiagCode constant of fe0/src/diag.fe, and an entry of the message table.
DIAG_CODE: re.Pattern[str] = re.compile(r"^pub const (\w+): DiagCode =", re.M)
MESSAGE: re.Pattern[str] = re.compile(r"Message \{ code: (\w+), text:")


def check_messages() -> list[FailureMessage]:
    """Returns a message for each error code of diag.fe that has no message, or more than one.

    It also returns a message when diag.fe has no error code or messages.fe has no message, since
    then the patterns no longer match the layout of the file.
    """
    diag = fegen.FE0 / "src/diag.fe"
    messages = CLI / "src/messages.fe"
    codes = DIAG_CODE.findall(diag.read_text())
    named = MESSAGE.findall(messages.read_text())
    empty = [FailureMessage(f"{path.relative_to(ROOT)}: no entry matches {pattern.pattern!r}")
             for path, pattern, found in [(diag, DIAG_CODE, codes), (messages, MESSAGE, named)]
             if not found]
    return empty + [FailureMessage(f"{messages.relative_to(ROOT)}: {c} has {named.count(c)}"
                                   " messages, not 1")
                    for c in codes if named.count(c) != 1]


def main() -> None:
    fe_test = embed.requested_fe_test(embed.parser(__doc__).parse_args())
    build()
    paths = sorted(p.relative_to(ROOT) for p in [*embed.CORPUS.glob("*.fe"), *gen.GEN.glob("*.fe")])
    rejects = embed.load_rejects()
    with ThreadPoolExecutor() as pool:
        runs = list(pool.map(Run.read, paths))
        misjudged = [m for m in pool.map(misjudgement, rejects) if m is not None]
    programs = [r.program() for r in runs if r.compiled()]
    uncompiled = [UncompiledProgram(r.path, r.said()) for r in runs if not r.compiled()]
    print(f"the CLI compiles {len(programs)} of {len(paths)} programs and rejects"
          f" {len(rejects) - len(misjudged)} of {len(rejects)} reject programs as expected")
    failures = [*(FailureMessage(str(u)) for u in uncompiled),
                *(FailureMessage(str(m)) for m in misjudged), *check_messages()]
    if fe_test and programs:
        shutil.rmtree(OUT, ignore_errors=True)
        batches = [b.write() for b in embed.Batch.split(OUT, programs)]
        failures += embed.run_batches(batches, fe_test)
    sys.exit("\n".join(failures) or None)


if __name__ == "__main__":
    main()
